"""DeepLTL LetterEnv-v0 (DQN) adapter for the generic confirmatory campaign runner.

Evaluation design (frozen after review): each of the 50 published formulas is
evaluated against 20 *independently random* maps per subject, generated by
LetterEnv-v0's own official reset distribution (``use_fixed_map=False``, the
environment's default) -- not the paired ``world_info_N.pkl`` files.

The paired worlds remain official corpus provenance (see
``tlrl_benchmarks.letter_env.adapter.load_world_layout`` and
``corpus_manifest.json``) and a canonical smoke/compatibility check, but are
deliberately not used to constrain confirmatory episodes: with a deterministic
(epsilon=0) evaluation policy, ``LetterEnv.reset()`` always sets
``self.agent = (0, 0)``, so pinning the map as well would make every episode
for a given (subject, formula) pair identical -- fake replication, not signal.
Holding the map fixed and only the policy random would recreate the same
problem in reverse.  Genuine within-cell variation requires the map itself to
vary, which is exactly what the official random-map reset distribution does
when seeded per episode.
"""

